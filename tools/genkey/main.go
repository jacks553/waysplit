// Command genkey даёт расширению постоянный ID (SPEC, раздел 4).
//
// Делает ключ RSA-2048 (или берёт уже созданный), кладёт открытую часть в поле "key"
// файла extension/manifest.json, а ID расширения — в host/extid.go, откуда его берёт
// команда install компаньона. ID = первые 32 hex-символа SHA-256 от открытого ключа
// в DER, где цифры 0–f заменены буквами a–p.
//
// Запуск из папки tools:  go run ./genkey        (ключ есть — ID не меняется)
//
//	go run ./genkey -new   (новый ключ — ID расширения поменяется!)
package main

import (
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

// Приватный ключ лежит здесь и в git не попадает (*.pem в .gitignore).
const keyFile = "tools/genkey/private-key.pem"

func main() {
	fresh := flag.Bool("new", false, "сделать новый ключ (ID расширения поменяется)")
	flag.Parse()
	if err := run(*fresh); err != nil {
		fmt.Fprintln(os.Stderr, "Ошибка:", err)
		os.Exit(1)
	}
}

func run(fresh bool) error {
	root, err := findRoot()
	if err != nil {
		return err
	}
	keyPath := filepath.Join(root, keyFile)
	key, created, err := loadOrCreate(keyPath, fresh)
	if err != nil {
		return err
	}
	der, err := x509.MarshalPKIXPublicKey(&key.PublicKey)
	if err != nil {
		return err
	}
	id := ExtensionID(der)
	manifest := filepath.Join(root, "extension", "manifest.json")
	if err := setManifestKey(manifest, base64.StdEncoding.EncodeToString(der)); err != nil {
		return err
	}
	if err := writeExtID(filepath.Join(root, "host", "extid.go"), id); err != nil {
		return err
	}
	if created {
		fmt.Println("Создан новый ключ:", keyPath)
		fmt.Println("Сохраните копию этого файла в надёжном месте; в git он не попадает.")
	} else {
		fmt.Println("Ключ уже был, ID не изменился:", keyPath)
	}
	fmt.Println("ID расширения:", id)
	fmt.Println("Обновлены extension/manifest.json (поле key) и host/extid.go.")
	fmt.Println("Пересоберите компаньон и выполните install, если ID поменялся.")
	return nil
}

// ExtensionID — ID расширения Chrome по открытому ключу в DER (SubjectPublicKeyInfo).
func ExtensionID(der []byte) string {
	sum := sha256.Sum256(der)
	id := []byte(hex.EncodeToString(sum[:16]))
	for i, c := range id {
		if c <= '9' {
			id[i] = 'a' + (c - '0')
		} else {
			id[i] = 'a' + 10 + (c - 'a')
		}
	}
	return string(id)
}

func loadOrCreate(path string, fresh bool) (*rsa.PrivateKey, bool, error) {
	if !fresh {
		data, err := os.ReadFile(path)
		if err == nil {
			block, _ := pem.Decode(data)
			if block == nil {
				return nil, false, fmt.Errorf("%s: не PEM-файл", path)
			}
			k, err := x509.ParsePKCS8PrivateKey(block.Bytes)
			if err != nil {
				return nil, false, fmt.Errorf("%s: %v", path, err)
			}
			rk, ok := k.(*rsa.PrivateKey)
			if !ok {
				return nil, false, fmt.Errorf("%s: ключ не RSA", path)
			}
			return rk, false, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return nil, false, err
		}
	}
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return nil, false, err
	}
	der, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, false, err
	}
	if err := os.WriteFile(path, pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}), 0o600); err != nil {
		return nil, false, err
	}
	return key, true, nil
}

var keyRe = regexp.MustCompile(`"key"\s*:\s*"[^"]*"`)

// setManifestKey меняет только значение поля "key", остальной файл не трогает.
func setManifestKey(path, key string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !keyRe.Match(data) {
		return fmt.Errorf("%s: нет поля \"key\"", path)
	}
	out := keyRe.ReplaceAllLiteral(data, []byte(`"key": "`+key+`"`))
	return os.WriteFile(path, out, 0o644)
}

func writeExtID(path, id string) error {
	src := "// Code generated by tools/genkey. DO NOT EDIT.\n\npackage main\n\n" +
		"// extensionID — постоянный ID расширения (из поля key в extension/manifest.json).\n" +
		"const extensionID = \"" + id + "\"\n"
	return os.WriteFile(path, []byte(src), 0o644)
}

// findRoot — папка проекта: та, где лежат SPEC.md и extension/.
func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "SPEC.md")); err == nil {
			if fi, err := os.Stat(filepath.Join(dir, "extension")); err == nil && fi.IsDir() {
				return dir, nil
			}
		}
		up := filepath.Dir(dir)
		if up == dir {
			return "", errors.New("не найдена папка проекта (с SPEC.md и extension) — запускайте из папки проекта или из tools")
		}
		dir = up
	}
}
