// Тексты компаньонов 1.0.0 и 1.1.0. У них нет фраз с кодом — только готовый русский текст,
// поэтому расширение узнаёт сами тексты и показывает их на языке окна. Незнакомый текст
// показывается как есть. Сюда же — тексты, которые прежние версии расширения записали в хранилище.

// Почему сервер не ответил на пинг: текст → код фразы компаньона (ключ словаря host.<код>).
const PING = new Map([
  ['Сервер не отвечает (возможно, заблокирован UDP)', 'ping_no_response_udp'],
  ['Сервер не отвечает', 'ping_no_response'],
  ['сервер не запущен в ядре', 'ping_not_in_core'],
]);
const CORE_PORT = /^ядро не слушает порт (\d+)$/;

// legacyPhrase — фраза { msg, params? } по тексту старого компаньона; текст незнаком — null.
export function legacyPhrase(text) {
  const s = String(text ?? '');
  const port = CORE_PORT.exec(s);
  if (port) return { msg: 'ping_core_port', params: { port: Number(port[1]) } };
  return PING.has(s) ? { msg: PING.get(s) } : null;
}

// NO_ANSWER — причина «нет ответа», если компаньон её не назвал. Так она записывается в хранилище
// (как и до 1.2.0: прежние версии покажут её как есть), а окно показывает её по ключу common.noAnswer.
export const NO_ANSWER = 'нет ответа';
